class FirstPromptTests(unittest.TestCase):
    def test_skips_injected_text_and_command_records(self):
        rows = [
            _user("<local-command-caveat>Caveat: generated by commands"
                  "</local-command-caveat>", "2026-11-01T01:00:00Z", isMeta=True),
            _user("<command-name>/clear</command-name>", "2026-11-01T01:00:01Z"),
            _user("<local-command-stdout></local-command-stdout>", "2026-11-01T01:00:02Z"),
            _user([{"type": "text", "text": "Skill body text"}], "2026-11-01T01:00:03Z", isMeta=True),
            _user("Summary of earlier work", "2026-11-01T01:00:04Z",
                  isCompactSummary=True),
            _user([{"type": "text", "text": "Build the visit pack for school A"}], "2026-11-01T01:01:00Z"),
            _asst([{"type": "text", "text": "ok"}], "2026-11-01T01:02:00Z"),
        ]
        row = _run_single_row_session(rows, SID)
        self.assertEqual(row["first_prompt"], "Build the visit pack for school A")

    def test_skips_records_labelled_as_not_typed_by_a_person(self):
        rows = [
            _user("message from another session", "2026-11-01T01:00:00Z",
                  promptSource="sdk", entrypoint="cli"),
            _typed("the real request", "2026-11-01T01:01:00Z"),
            _asst([{"type": "text", "text": "ok"}], "2026-11-01T01:02:00Z"),
        ]
        row = _run_single_row_session(rows, SID)
        self.assertEqual(row["first_prompt"], "the real request")

    def test_skips_unlabelled_records_from_a_programmatic_entrypoint(self):
        rows = [
            _user("scripted request", "2026-11-01T01:00:00Z",
                  entrypoint="sdk-cli"),
            _typed("the real request", "2026-11-01T01:01:00Z"),
            _asst([{"type": "text", "text": "ok"}], "2026-11-01T01:02:00Z"),
        ]
        row = _run_single_row_session(rows, SID)
        self.assertEqual(row["first_prompt"], "the real request")

    def test_skips_blank_text_blocks(self):
        rows = [
            _user([{"type": "text", "text": "   "},
                   {"type": "text", "text": "the real request"}],
                  "2026-11-01T01:00:00Z"),
            _asst([{"type": "text", "text": "ok"}], "2026-11-01T01:02:00Z"),
        ]
        row = _run_single_row_session(rows, SID)
        self.assertEqual(row["first_prompt"], "the real request")


class ActiveMinutesTests(unittest.TestCase):
    def test_idle_gaps_over_30_minutes_are_not_counted(self):
        rows = [
            _user("start", "2026-11-01T01:00:00Z"),
            _asst([{"type": "text", "text": "ok"}], "2026-11-01T01:10:00Z"),
            # 60-minute idle gap
            _user("back", "2026-11-01T02:10:00Z"),
            _asst([{"type": "text", "text": "ok"}], "2026-11-01T02:15:00Z"),
        ]
        row = _run_single_row_session(rows, SID)
        self.assertEqual(row["duration_minutes"], 75)  # full span, unchanged
        self.assertEqual(row["active_minutes"], 15)


class MergeTests(unittest.TestCase):
    def _transcript_row(self):
        return {
            "session_id": SID, "start_time": "2026-11-01T01:00:00Z",
            "project_path": "/x/proj", "duration_minutes": 455,
            "active_minutes": 335, "user_message_count": 44,
            "assistant_message_count": 300, "tool_counts": {"Agent": 2},
            "user_interruptions": 1, "tool_errors": 3,
            "uses_task_agent": True, "uses_subagent": True,
            "uses_mcp": True, "uses_web_search": False,
            "uses_web_fetch": False, "first_prompt": "the real request",
            "git_commits": 13,
            # the scanner does not count line changes
            "lines_added": 0, "lines_removed": 0, "files_modified": 0,
        }

    def _tail_only_meta(self):
        return {
            "session_id": SID, "start_time": "2026-11-01T05:00:00Z",
            "project_path": "/x/proj", "duration_minutes": 228,
            "user_message_count": 8, "assistant_message_count": 40,
            "tool_counts": {}, "user_interruptions": 0, "tool_errors": 0,
            "uses_task_agent": False, "uses_mcp": False,
            "uses_web_search": False, "uses_web_fetch": False,
            "first_prompt": "go with the recommendations",
            "git_commits": 5,
            "lines_added": 120, "lines_removed": 30, "files_modified": 4,
        }

    def test_transcript_row_wins_on_counted_fields(self):
        merged = aggregate.merge_scoring_metas(
            {SID: self._tail_only_meta()}, {SID: self._transcript_row()})
        m = merged[SID]
        self.assertEqual(m["user_message_count"], 44)
        self.assertEqual(m["first_prompt"], "the real request")
        self.assertEqual(m["duration_minutes"], 455)
        self.assertEqual(m["active_minutes"], 335)
        self.assertEqual(m["git_commits"], 13)
        self.assertEqual(m["start_time"], "2026-11-01T01:00:00Z")
        self.assertTrue(m["uses_subagent"])

    def test_meta_fills_line_counts_the_scanner_does_not_compute(self):
        merged = aggregate.merge_scoring_metas(
            {SID: self._tail_only_meta()}, {SID: self._transcript_row()})
        m = merged[SID]
        self.assertEqual(m["lines_added"], 120)
        self.assertEqual(m["lines_removed"], 30)
        self.assertEqual(m["files_modified"], 4)

    def test_orphan_subagent_row_does_not_replace_parent_meta(self):
        # Parent transcript rotated away; only its subagent runs remain.
        orphan = {"session_id": SID, "start_time": "2026-11-01T06:00:00Z",
                  "project_path": "", "duration_minutes": 3,
                  "active_minutes": 3, "user_message_count": 0,
                  "first_prompt": "", "git_commits": 0,
                  "cache_read_input_tokens": 900,
                  "model_counts": {"claude-sonnet-5-5": 4},
                  "orphan_subagent_only": True}
        merged = aggregate.merge_scoring_metas(
            {SID: self._tail_only_meta()}, {SID: orphan})
        m = merged[SID]
        self.assertEqual(m["user_message_count"], 8)
        self.assertEqual(m["first_prompt"], "go with the recommendations")
        self.assertEqual(m["duration_minutes"], 228)
        self.assertEqual(m["project_path"], "/x/proj")
        self.assertNotIn("active_minutes", m)
        # scanner-only extras still come through
        self.assertEqual(m["cache_read_input_tokens"], 900)

    def test_orphan_subagent_row_counts_as_delegation(self):
        # Subagent runs survived for this session, so it did delegate, even
        # when the tail-only session-meta did not see the Agent call.
        orphan = {"session_id": SID, "start_time": "2026-11-01T06:00:00Z",
                  "uses_subagent": True, "orphan_subagent_only": True}
        merged = aggregate.merge_scoring_metas(
            {SID: self._tail_only_meta()}, {SID: orphan})
        s = aggregate.build_sessions(merged, {}, timezone.utc)[0]
        self.assertTrue(s["uses_task_agent"])

    def test_meta_only_session_is_kept(self):
        merged = aggregate.merge_scoring_metas({SID: self._tail_only_meta()}, {})
        self.assertEqual(merged[SID]["user_message_count"], 8)

    def test_transcript_without_meta_stays_out_of_scoring_pool(self):
        merged = aggregate.merge_scoring_metas({}, {SID: self._transcript_row()})
        self.assertEqual(merged, {})


class BuildSessionsTests(unittest.TestCase):
    def _meta(self, **over):
        m = {"session_id": SID, "start_time": "2026-11-01T01:00:00Z",
             "project_path": "/x/proj", "duration_minutes": 455}
        m.update(over)
        return m

    def test_work_time_uses_active_minutes_when_present(self):
        s = aggregate.build_sessions(
            {SID: self._meta(active_minutes=335)}, {}, timezone.utc)[0]
        self.assertEqual(s["duration_min"], 335)

    def test_work_time_falls_back_to_duration_without_segments(self):
        s = aggregate.build_sessions({SID: self._meta()}, {}, timezone.utc)[0]
        self.assertEqual(s["duration_min"], 455)

    def test_delegation_counts_only_real_subagent_dispatch(self):
        # Task-list tools alone set the broad flag but are not delegation.
        s = aggregate.build_sessions(
            {SID: self._meta(uses_task_agent=True, uses_subagent=False)},
            {}, timezone.utc)[0]
        self.assertFalse(s["uses_task_agent"])

    def test_delegation_falls_back_for_meta_only_sessions(self):
        s = aggregate.build_sessions(
            {SID: self._meta(uses_task_agent=True)}, {}, timezone.utc)[0]
        self.assertTrue(s["uses_task_agent"])


class MethodVersionTests(unittest.TestCase):
    ANALYSIS = {"meta": {"total_sessions": 3,
                         "method_version": 2},
                "scores": {}, "ledger": {}}

    def test_snapshot_records_method_version(self):
        self.assertEqual(
            report_render.snapshot_entry(self.ANALYSIS)["method_version"], 2)

    def test_snapshot_from_old_analysis_is_version_one(self):
        entry = report_render.snapshot_entry({"meta": {}, "scores": {}})
        self.assertEqual(entry["method_version"], 1)

    def test_malformed_version_matches_no_method(self):
        for bad in ("2", True, None, 2.0):
            a = {"meta": {"method_version": bad}, "scores": {}}
            v = report_render.analysis_method_version(a)
            self.assertNotIn(v, (1, 2), bad)
        with tempfile.TemporaryDirectory() as td:
            hist = Path(td) / "h.jsonl"
            hist.write_text("\n".join([
                json.dumps({"date": "2026-07-14", "method_version": True}),
                json.dumps({"date": "2026-07-15", "method_version": "1"}),
                json.dumps({"date": "2026-07-16"}),
            ]) + "\n")
            self.assertEqual(
                [e["date"] for e in read_history_snapshots(hist, method_version=1)],
                ["2026-07-16"])
        # An unknown method (0, negative, or not an int) is never comparable,
        # not even with history lines that are unknown the same way.
        with tempfile.TemporaryDirectory() as td:
            hist = Path(td) / "h.jsonl"
            hist.write_text("\n".join([
                json.dumps({"date": "2026-07-14", "method_version": True}),
                json.dumps({"date": "2026-07-15", "method_version": 0}),
                json.dumps({"date": "2026-07-16", "method_version": "2"}),
                json.dumps({"date": "2026-07-17", "method_version": -1}),
            ]) + "\n")
            for v in (0, -1):
                self.assertEqual(read_history_snapshots(hist, method_version=v), [])
        self.assertEqual(report_render.method_version_of({"method_version": -1}), 0)

    def test_reader_keeps_only_same_method_snapshots(self):
        with tempfile.TemporaryDirectory() as td:
            hist = Path(td) / "h.jsonl"
            hist.write_text("\n".join([
                json.dumps({"date": "2026-07-15", "schema_version": 1}),
                json.dumps({"date": "2026-11-20", "schema_version": 1,
                            "method_version": 2}),
            ]) + "\n")
            self.assertEqual(
                [e["date"] for e in read_history_snapshots(hist, method_version=2)],
                ["2026-11-20"])
            self.assertEqual(
                [e["date"] for e in read_history_snapshots(hist, method_version=1)],
                ["2026-07-15"])
            # no filter requested: every valid line, as before
            self.assertEqual(len(read_history_snapshots(hist)), 2)

    def test_appended_line_carries_method_version(self):
        with tempfile.TemporaryDirectory() as td:
            hist = Path(td) / "h.jsonl"
            append_history_snapshot(hist, self.ANALYSIS, "self")
            entry = json.loads(hist.read_text().strip())
        self.assertEqual(entry["method_version"], 2)


class MethodStampTests(unittest.TestCase):
    """analysis-data.json is stamped method 2 only when the run read full
    transcripts; a session-meta-only run is still counted the old way."""

    def _run(self, with_transcripts, rows_text=None, redacted=False):
        import subprocess
        with tempfile.TemporaryDirectory() as td:
            td = Path(td)
            meta_dir = td / "usage-data" / "session-meta"
            meta_dir.mkdir(parents=True)
            row = {"session_id": SID, "start_time": "2026-11-01T01:00:00Z",
                   "project_path": "/x/proj", "duration_minutes": 10,
                   "user_message_count": 2, "input_tokens": 1,
                   "output_tokens": 1}
            (meta_dir / f"{SID}.json").write_text(json.dumps(row))
            cmd = [sys.executable, str(SKILL_DIR / "scripts" / "aggregate.py"),
                   "--data-dir", str(td / "usage-data"),
                   "--output", str(td / "a.json")]
            if with_transcripts:
                (td / "tr.jsonl").write_text(
                    json.dumps(row) + "\n" if rows_text is None else rows_text)
                cmd += ["--transcript-rows", str(td / "tr.jsonl")]
            if redacted:
                other = dict(row, session_id=SID.replace("1", "9"))
                (td / "red.jsonl").write_text(json.dumps(other) + "\n")
                cmd += ["--extra-redacted", str(td / "red.jsonl")]
            r = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            return json.loads((td / "a.json").read_text())["meta"]["method_version"]

    def test_transcript_run_is_method_two(self):
        self.assertEqual(self._run(True), aggregate.METHOD_VERSION)

    def test_session_meta_only_run_is_method_one(self):
        self.assertEqual(self._run(False), 1)

    def test_empty_transcript_rows_file_is_method_one(self):
        self.assertEqual(self._run(True, rows_text=""), 1)

    def test_empty_transcript_rows_plus_redacted_rows_is_method_one(self):
        self.assertEqual(self._run(True, rows_text="", redacted=True), 1)

    def test_redacted_rows_are_counted_the_old_way(self):
        import subprocess
        with tempfile.TemporaryDirectory() as td:
            td = Path(td)
            (td / "usage-data" / "session-meta").mkdir(parents=True)
            row = {"session_id": SID, "start_time": "2026-11-01T01:00:00Z",
                   "project_path": "/x/proj", "duration_minutes": 75,
                   "active_minutes": 15, "uses_task_agent": True,
                   "uses_subagent": False, "user_message_count": 2,
                   "input_tokens": 1, "output_tokens": 1}
            (td / "red.jsonl").write_text(json.dumps(row) + "\n")
            r = subprocess.run(
                [sys.executable, str(SKILL_DIR / "scripts" / "aggregate.py"),
                 "--data-dir", str(td / "usage-data"),
                 "--extra-redacted", str(td / "red.jsonl"),
                 "--output", str(td / "a.json")],
                capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr)
            data = json.loads((td / "a.json").read_text())
        self.assertEqual(data["meta"]["method_version"], 1)
        s = data["_sessions"][0]
        self.assertEqual(s["duration_min"], 75)
        self.assertTrue(s["uses_task_agent"])


